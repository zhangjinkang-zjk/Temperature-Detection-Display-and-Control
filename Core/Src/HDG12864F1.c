void Lcd_GPIO_Configuration(void) {
    GPIO_InitTypeDef GPIO_InitStruct = {0};
    
    // 启用 GPIOA 和 GPIOB 时钟
    __HAL_RCC_GPIOA_CLK_ENABLE();
    __HAL_RCC_GPIOB_CLK_ENABLE();
    
    // 配置 PA4, PA5, PA6, PA7 和 PB1 为输出
    GPIO_InitStruct.Pin = GPIO_PIN_4 | GPIO_PIN_5 | GPIO_PIN_6 | GPIO_PIN_7;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOA, &GPIO_InitStruct);
    
    // 配置 PB1 为输出
    GPIO_InitStruct.Pin = GPIO_PIN_1;
    GPIO_InitStruct.Mode = GPIO_MODE_OUTPUT_PP;
    GPIO_InitStruct.Speed = GPIO_SPEED_FREQ_HIGH;
    HAL_GPIO_Init(GPIOB, &GPIO_InitStruct);
}

void wrt_cmd(uint8_t command) {
    uint8_t i = 8;
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);  // 选择 CS (低电平有效)
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, GPIO_PIN_RESET);  // A0 选择命令模式 (低电平)
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);  // 设置 SCL 为低电平
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_6, GPIO_PIN_SET);    // RD 直接接VCC，忽略操作
    while(i--) {
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);   // 设置 SCL 为低电平
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, (command & 0x80) ? GPIO_PIN_SET : GPIO_PIN_RESET);  // SI 数据位
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);     // 设置 SCL 高低电平
        command <<= 1;
        HAL_Delay_us(15);
    }
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET); // 设置 SCL 为低电平
}

void wrt_dt(uint8_t data_) {
    uint8_t i = 8;
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_4, GPIO_PIN_RESET);  // 选择 CS (低电平有效)
    HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, GPIO_PIN_SET);    // A0 选择数据模式 (高电平)
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);  // 设置 SCL 为低电平
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_6, GPIO_PIN_SET);    // RD 直接接VCC，忽略操作
    while(i--) {
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET);   // SCL 下降沿
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_7, (data_ & 0x80) ? GPIO_PIN_SET : GPIO_PIN_RESET);  // SI 数据位
        HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_SET);     // SCL 上升沿
        data_ <<= 1;
        HAL_Delay_us(15);
    }
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_5, GPIO_PIN_RESET); // SCL 置低
}


void HDG12864F1_SetColumnAddress(uint8_t address) {
    wrt_cmd(0x10 + (address >> 4));
    wrt_cmd(0x00 + (address & 0x0F));
}                      //设置列地址，范围为0-127

void HDG12864F1_SetPageAddress(uint8_t pageAddress) {
    wrt_cmd(0xb0 + pageAddress);
}                     //设置行地址，范围为0-63

void HDG12864F1_SetStartLine(uint8_t line) {
    wrt_cmd(0x40 + line);
}

void HDG12864F1_Init(void) {
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_6, GPIO_PIN_RESET);  // RST 拉低
    Delay_ms(50);     // 等待 50ms
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_6, GPIO_PIN_SET);    // RST 拉高
    wrt_cmd(0xAE);   // 关闭显示
    wrt_cmd(0x00);   // 设置列地址高 4 位
    wrt_cmd(0x10);   // 设置列地址低 4 位
    wrt_cmd(0x40);   // 设置起始行地址
    wrt_cmd(0xB0);   // 设置页地址
    wrt_cmd(0x81);   // 设置对比度
    wrt_cmd(0xFF);   // 最大对比度
    wrt_cmd(0xA1);   // 设置显示反向（仿真）
    wrt_cmd(0xA6);   // 设置正常显示（仿真）
//	wrt_cmd(0xA0);   // 设置显示正向(实测)
//  wrt_cmd(0xC0);   // 设置正常显示(实测)
    wrt_cmd(0xA4);   // 设置自动刷新
    wrt_cmd(0xD3);   // 设置显示偏移
    wrt_cmd(0x00);   // 显示偏移量
    wrt_cmd(0x8D);   // 设置电荷泵
    wrt_cmd(0x14);   // 开启电荷泵
    wrt_cmd(0xAF);   // 开启显示
}

void HDG12864F1_Clear(void) {
    uint8_t i, j;
    for (i = 0; i < 8; i++) {
        HDG12864F1_SetPageAddress(i);
        HDG12864F1_SetColumnAddress(0);
        for (j = 0; j < 128; j++) {
            HDG12864F1_WriteData(0x00);
        }
    }
}

void HDG12864F1_ClearArea(uint8_t column, uint8_t page, uint8_t width) {
    uint8_t i;
    HDG12864F1_SetColumnAddress(column);
    HDG12864F1_SetPageAddress(page);
    for (i = 0; i < width; i++) {
        HDG12864F1_WriteData(0x00);
    }
}

void HDG12864F1_WriteData(uint8_t data_) {
    wrt_dt(data_);
}

